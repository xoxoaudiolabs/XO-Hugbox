# Inline every local <script src="..."> (classic or type="module") of an HTML page so it becomes one
# self-contained file: opens by double-click from file://, in any viewer, and publishes as one Artifact.
#   python bundle.py src/index.html index.html
import os, re, sys
src, dst = sys.argv[1], sys.argv[2]
base = os.path.dirname(os.path.abspath(src))
html = open(src, encoding="utf-8").read()
def inline(m):
    typ, url = m.group(1) or "", m.group(2)
    if re.match(r"^[a-z]+:|^//", url): return m.group(0)          # leave CDN scripts alone
    js = open(os.path.join(base, url), encoding="utf-8").read().replace("</script", "<" + chr(92) + "/script")
    return "<script" + typ + ">/* " + url + " */\n" + js + "\n</script>"
out = re.sub(r'<script( type="module")? src="([^"]+)"></script>', inline, html)
rel = os.path.relpath(os.path.abspath(src), os.path.dirname(os.path.abspath(dst))).replace("\\", "/")
out = out.replace("<!doctype html>", "<!doctype html>\n<!-- GENERATED by bundle.py from " + rel + " - edit the sources, then re-run. -->", 1)
open(dst, "w", encoding="utf-8", newline="\n").write(out)
print(dst, len(out), "bytes")
