# Pack layout.py + PCB dump (pcb.json from dump_pcb.py) + the two STLs into ../src/data.js
# (a classic <script>, so the guide opens from file:// with no server).
# Run from this folder:  python gen_data.py
import base64, json, os, re, struct, sys
here = os.path.dirname(os.path.abspath(__file__))
hw = os.path.normpath(os.path.join(here, "../../../hardware"))
sys.path.insert(0, hw)
import layout as L

lay = {k: v for k, v in vars(L).items() if not k.startswith("_") and isinstance(v, (int, float, tuple, list, dict))}
lay["cx"] = [L.cx(i) for i in range(4)]; lay["cy"] = [L.cy(j) for j in range(4)]

num = re.compile(r"vertex\s+(\S+)\s+(\S+)\s+(\S+)")
def stl_b64(path):
    vals = []
    with open(path) as f:
        for line in f:
            m = num.search(line)
            if m: vals.extend(round(float(x) * 100) for x in m.groups())   # 0.01 mm int16
    assert max(abs(v) for v in vals) < 32767
    return base64.b64encode(struct.pack("<%dh" % len(vals), *vals)).decode(), len(vals) // 9

shell, ns = stl_b64(os.path.join(hw, "mechanical/xo_hugbox_shell.stl"))
plate, np_ = stl_b64(os.path.join(hw, "mechanical/xo_hugbox_top_plate.stl"))
pcb = json.load(open(os.path.join(here, "pcb.json")))
oled = json.load(open(os.path.join(here, "oled_frame.json")))["b64"]   # from capture_oled.js
data = {"layout": lay, "pcb": pcb, "stl": {"shell": shell, "plate": plate, "scale": 0.01}, "oled": oled}
with open(os.path.join(here, "../src/data.js"), "w") as f:
    f.write("// Generated by tools/gen_data.py from hardware/layout.py, hardware/pcb/xo_hugbox.kicad_pcb and the STLs. Do not edit.\n")
    f.write("window.HUGBOX_DATA = "); json.dump(data, f, separators=(",", ":")); f.write(";\n")
print("shell tris", ns, "plate tris", np_, "bytes", os.path.getsize(os.path.join(here, "../src/data.js")))
