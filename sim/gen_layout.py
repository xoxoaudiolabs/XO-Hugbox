# Writes sim/src/layout.js (window.HUGBOX_LAYOUT) from hardware/layout.py so the emulator draws the real plate.
# Run from sim/:  python gen_layout.py
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, "..", "hardware"))
import layout as L
lay = {k: v for k, v in vars(L).items() if not k.startswith("_") and isinstance(v, (int, float, tuple, list, dict))}
lay["cx"] = [L.cx(i) for i in range(4)]; lay["cy"] = [L.cy(j) for j in range(4)]
with open(os.path.join(here, "src", "layout.js"), "w") as f:
    f.write("// Generated by gen_layout.py from hardware/layout.py (plate coords, mm, y up). Do not edit.\n")
    f.write("window.HUGBOX_LAYOUT = " + json.dumps(lay) + ";\n")
print("ok")
