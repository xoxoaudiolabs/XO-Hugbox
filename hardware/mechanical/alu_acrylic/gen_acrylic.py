# XO-Hugbox variant: clear acrylic faceplate, 4 laser-cut layers (generated from layout.py).
# Run from this folder:  PYTHONPATH=../.. python gen_acrylic.py
# Writes xo_hugbox_acrylic.scad; export each layer's DXF with OpenSCAD -D layer=N (see README.md).
import json, os
import layout as L

here = os.path.dirname(os.path.abspath(__file__))
pcb = json.load(open(os.path.join(here, "../../../docs/build-guide/tools/pcb.json")))   # v1.0 board, plate coords

# Header rows / lead ends that come up through the top of the board under layer 1 (modules mounted on the back etc.)
RELIEF_REFS = ["U1", "U2", "U3", "U4", "J9", "J11", "J13", "J_MTDI", "R1", "R2"]
reliefs = []
for f in pcb["fps"]:
    if f["ref"] in RELIEF_REFS:
        reliefs.append([[round(p["xy"][0], 2), round(p["xy"][1], 2)] for p in f["pads"]])
assert len(reliefs) == len(RELIEF_REFS), "pcb.json is missing a footprint"

pcb_top = L.Z_PCB + L.PCB_T
z1 = pcb_top + L.ACR_SPACER                 # layer 1 underside (= aluminium wall top)
z2 = z1 + L.ACR_UNDER_T                     # layer 2 underside
z3 = z2 + L.ACR_SW_T                        # layer 3 underside (= switch plate top, PCB +5.0)
z4 = z3 + L.ACR_KNOB_T                      # layer 4 underside
assert abs(z3 - (pcb_top + L.ACR_SW_TOP)) < 1e-6
can_top = pcb_top + L.POT_BODY_H
lug_reach = L.POT_CAN_D / 2 + L.POT_LUG_L
strip_front = lug_reach + 1.0 + 1.6
strip_x0 = L.cx(0) - 10.4
oled_pcb_h = L.OLED_PCB_POCKET[1] - L.OLED_PCB_POCKET[0]
pwr_window = L.PWR_BODY_H > (z2 - pcb_top)          # body taller than layer 2's underside -> open the body footprint
mic_face = L.ACR_MIC_SPACER + L.MIC_PCB_T + 0.5     # label face + solder, above the PCB top
assert mic_face <= z2 - pcb_top, "mic would hit layer 2"
top_holes = [list(h) for i, h in enumerate(L.HOLES) if i not in L.SUPPORT_ONLY]

scad = f"""// XO-Hugbox - clear acrylic faceplate, 4 laser-cut layers (generated by gen_acrylic.py from layout.py; do not edit)
// layer=1..4 -> that layer's 2D outline (export DXF/SVG); layer=0 -> 3D stack in shell coordinates (preview).
// 1: under-layer {L.ACR_UNDER_T} mm   2: switch plate {L.ACR_SW_T} mm   3: knob spacer {L.ACR_KNOB_T} mm   4: knob top {L.ACR_KNOB_T} mm
layer=0;
W={L.W}; H={L.H}; r=3; pitch={L.P};
z1={z1:.2f}; z2={z2:.2f}; z3={z3:.2f}; z4={z4:.2f};   // layer undersides (shell z); can top {can_top:.2f}
t1={L.ACR_UNDER_T}; t2={L.ACR_SW_T}; t3={L.ACR_KNOB_T}; t4={L.ACR_KNOB_T};
pot_y={L.POT_Y}; can_d={L.ACR_CAN_D:.2f}; shaft_d=7.5; lug_reach={lug_reach:.2f}; strip_front={strip_front:.2f}; strip_x0={strip_x0:.3f};
oled_c=[{L.OLED_C[0]:.2f},{L.OLED_C[1]:.2f}]; oled_pcb=[36.4,{oled_pcb_h:.2f}]; oled_pcb_cy={sum(L.OLED_PCB_POCKET)/2:.2f};
oled_glass=[{L.OLED_GLASS[0]+1:.2f},{L.OLED_GLASS[1]+1:.2f}]; oled_glass_off={L.OLED_GLASS_OFF:.2f};
spk_c=[{L.SPK_C[0]:.2f},{L.SPK_C[1]:.2f}]; grille_r=10;
shift=[{L.SHIFT[0]},{L.SHIFT[1]}]; pwr=[{L.PWR[0]},{L.PWR[1]}]; pwr_window={str(pwr_window).lower()};
mic_c=[{L.MIC_C[0]},{L.MIC_C[1]}]; mic_d={L.MIC_D}; mic_hole={L.MIC_HOLE};
top_holes={top_holes};   // corners only: the knob strip has no screw (support post under it)
reliefs={reliefs};
function cx(i)={L.BORDER}+pitch/2+i*pitch; function cy(j)={L.BORDER}+pitch/2+j*pitch;
keys=[for(i=[0:3]) for(j=[0:3]) [cx(i),cy(j)], shift];
module sq(c,s) translate([c[0]-s[0]/2,c[1]-s[1]/2]) square(s);
module outline() offset(r=r) offset(delta=-r) square([W,H]);
module strip() translate([strip_x0,pot_y-strip_front]) offset(r=2) offset(delta=-2) square([W-3-strip_x0,strip_front+10.4]);
module screws(pts) for(p=pts) translate(p) circle(d=3.4,$fn=32);
module cans() for(i=[0:3]) translate([cx(i),pot_y]) circle(d=can_d,$fn=96);
module lugs() for(i=[0:3]) translate([cx(i)-7,pot_y-(lug_reach+1.0)]) square([14,lug_reach+1.0]);
module grille() for(dx=[-grille_r:4:grille_r]) for(dy=[-grille_r:4:grille_r]) if(dx*dx+dy*dy<=grille_r*grille_r)
  translate([spk_c[0]+dx,spk_c[1]+dy]) circle(d=2,$fn=24);
module pwr_cut() if(pwr_window) sq(pwr,[9.4,4.4]); else sq(pwr,[4.3,2.1]);

// 1: under-layer - switch pockets, every part on the board top, header rows, speaker grille (speaker face seals here)
module l1() difference(){{ outline();
  for(k=keys) sq(k,[16,16]);
  cans(); lugs();
  sq([oled_c[0],oled_pcb_cy],oled_pcb);
  translate(mic_c) circle(d=mic_d+0.8,$fn=96);
  sq(pwr,[9.4,4.4]);
  for(p=reliefs) hull() for(q=p) translate(q) circle(r=1.5,$fn=24);
  grille(); screws(top_holes);
}}
// 2: switch plate - 14 mm MX holes, OLED glass window, mic sound hole, grille
module l2() difference(){{ outline();
  for(k=keys) sq(k,[14,14]);
  cans(); lugs();
  sq([oled_c[0],oled_c[1]+oled_glass_off],oled_glass);
  translate(mic_c) circle(d=mic_hole,$fn=32);
  pwr_cut(); grille(); screws(top_holes);
}}
// 3: knob spacer - cans + solder lugs
module l3() difference(){{ strip(); cans(); lugs(); }}
// 4: knob top - shaft holes; the pot nuts clamp it to the cans
module l4() difference(){{ strip(); for(i=[0:3]) translate([cx(i),pot_y]) circle(d=shaft_d,$fn=64); }}

if(layer==1) l1(); else if(layer==2) l2(); else if(layer==3) l3(); else if(layer==4) l4();
else color("#cfe8ff",0.55){{
  translate([0,0,z1]) linear_extrude(t1) l1();
  translate([0,0,z2]) linear_extrude(t2) l2();
  translate([0,0,z3]) linear_extrude(t3) l3();
  translate([0,0,z4]) linear_extrude(t4) l4();
}}
"""
open(os.path.join(here, "xo_hugbox_acrylic.scad"), "w", newline="\n").write(scad)
print(f"layer undersides z1={z1:.2f} z2={z2:.2f} z3={z3:.2f} z4={z4:.2f} top={z4+L.ACR_KNOB_T:.2f} can_top={can_top:.2f}"
      f" pwr_window={pwr_window} mic_face=+{mic_face:.2f}")
